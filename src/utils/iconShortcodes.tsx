export function resolveIcon(shortcode: string): LucideIcon | null {
  const inner = shortcode.replace(/^:/, "").replace(/:$/, "");
  // Strip family prefix: material-, fontawesome-solid-, fontawesome-brands-, simple-, octicons-
  const name = inner
    .replace(/^material-/, "")
    .replace(/^fontawesome-solid-/, "")
    .replace(/^fontawesome-brands-/, "")
    .replace(/^fontawesome-regular-/, "")
    .replace(/^simple-/, "")
    .replace(/^octicons-/, "")
    .replace(/^emoji-/, "");

  return ICON_MAP[name] ?? null;
}

