export const ICON_SHORTCODE_REGEX =
  /:(material|fontawesome|simple|octicons|emoji)-[a-zA-Z0-9-]+:/g;

export function isIconShortcode(text: string): boolean {
  return /^:(material|fontawesome|simple|octicons|emoji)-[a-zA-Z0-9-]+:$/.test(text);
}
